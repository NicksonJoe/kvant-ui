import { resolveColors, toHex, type Rgba } from './color.ts';
import { MODES, type Accent, type TokenSets } from './dtcg.ts';

// Stubs: colours only. Typography, radii and motion follow once the Flutter and Filament themes are designed.

const GENERATED = 'Generated by @kvant/tokens from the DTCG sources. Do not edit.';

const pascal = (value: string): string => value.replace(/(^|-)(\w)/g, (_, _dash: string, letter: string) => letter.toUpperCase());
const camel = (value: string): string => value.replace(/-(\w)/g, (_, letter: string) => letter.toUpperCase());
const key = (name: string): string => name.replace(/^color-/, '');

const argb = ({ r, g, b, a }: Rgba): string =>
  `0x${[Math.round(a * 255), r, g, b].map((part) => part.toString(16).padStart(2, '0')).join('').toUpperCase()}`;

/** Flutter: one class of `Color` constants per mode, e.g. `KvantCobaltLight.accent`. */
export function buildDart(sets: TokenSets, accent: Accent): string {
  const classes = MODES.map((mode) => {
    const fields = [...resolveColors(sets, accent, mode)].map(([name, color]) => `  static const ${camel(key(name))} = Color(${argb(color)});`);
    return `abstract final class Kvant${pascal(accent)}${pascal(mode)} {\n${fields.join('\n')}\n}`;
  });
  return `// ${GENERATED}\n// Kvant colours, accent «${accent}».\nimport 'dart:ui';\n\n${classes.join('\n\n')}\n`;
}

/** Filament / Laravel: `return ['light' => ['accent' => '#1c71e2', …], 'dark' => […]];`. */
export function buildPhp(sets: TokenSets, accent: Accent): string {
  const modes = MODES.map((mode) => {
    const entries = [...resolveColors(sets, accent, mode)].map(([name, color]) => `        '${key(name)}' => '${toHex(color)}',`);
    return `    '${mode}' => [\n${entries.join('\n')}\n    ],`;
  });
  return `<?php\n\ndeclare(strict_types=1);\n\n// ${GENERATED}\n// Kvant colours, accent «${accent}».\n\nreturn [\n${modes.join('\n')}\n];\n`;
}
